/**
 * Freezes the generated mock book into db/seed-data.json.
 *
 * `src/lib/mockData.ts` builds its clients with a random generator at import
 * time, so the "book" changed on every page load — 48 different people each
 * time you refreshed. Capturing one draw and seeding the database from it makes
 * the demo stable, reviewable in a diff, and the same for every visitor.
 *
 * Run only when the demo book should intentionally change:
 *   node scripts/extract-seed-data.mjs
 */
import { build } from "esbuild";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const dir = await mkdtemp(join(tmpdir(), "seed-"));
const out = join(dir, "mockData.mjs");

await build({
  entryPoints: ["src/lib/mockData.ts"],
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "node",
  logLevel: "error",
});

const m = await import(`file://${out}`);
await rm(dir, { recursive: true, force: true });

const agentByName = new Map(m.agents.map((a) => [a.name, a.id]));

function agentId(name, context) {
  const id = agentByName.get(name);
  if (!id) throw new Error(`No agent record named "${name}" (referenced by ${context})`);
  return id;
}

// Policies are derived from clients positionally in mockData, so the client a
// policy belongs to is recoverable exactly — no name matching, which would be
// ambiguous when two generated clients share a name.
const eligible = m.clients.filter(
  (c) => c.status === "Active" || c.status === "Pending" || c.status === "Lapsed",
);
if (eligible.length !== m.policies.length) {
  throw new Error(
    `Policy derivation changed: ${eligible.length} eligible clients but ${m.policies.length} policies`,
  );
}

const clientsById = new Map(m.clients.map((c) => [c.id, c]));

const data = {
  // A note for whoever reads this file in a diff and wonders where it came from.
  _source: "generated by scripts/extract-seed-data.mjs from src/lib/mockData.ts",
  agents: m.agents,
  clients: m.clients.map((c) => ({ ...c, agentId: agentId(c.agent, `client ${c.id}`) })),
  policies: m.policies.map((p, i) => {
    const client = eligible[i];
    if (p.client !== client.name) {
      throw new Error(`Policy ${p.id} does not line up with client ${client.id}`);
    }
    return {
      id: p.id,
      clientId: client.id,
      carrier: p.carrier,
      planType: p.planType,
      status: p.status,
      premium: p.premium,
      commission: p.commission,
      effectiveDate: p.effectiveDate,
      renewalDate: p.renewalDate,
      agentId: agentId(p.agent, `policy ${p.id}`),
    };
  }),
  appointments: m.appointments.map((a) => {
    // Appointment client names are literals in the source and mostly name
    // prospects who are not in the generated book. Link the ones that do match;
    // leave the rest with a name and no client row, which is what the schema
    // models.
    const match = m.clients.find((c) => c.name === a.client);
    return {
      id: a.id,
      clientId: match ? match.id : null,
      clientName: a.client,
      agentId: agentId(a.agent, `appointment ${a.id}`),
      type: a.type,
      date: a.date,
      time: a.time,
      duration: a.duration,
      status: a.status,
      location: a.location,
      notes: a.notes ?? null,
    };
  }),
};

// Dates in mockData are computed as offsets from "today", so a fresh extract
// would shift every date. Record the basis so a later reader knows what the
// dates are relative to.
data._extractedOn = new Date().toISOString().slice(0, 10);

await writeFile("db/seed-data.json", `${JSON.stringify(data, null, 2)}\n`);

const linked = data.appointments.filter((a) => a.clientId).length;
console.log(
  `db/seed-data.json: ${data.agents.length} agents, ${data.clients.length} clients, ` +
    `${data.policies.length} policies, ${data.appointments.length} appointments ` +
    `(${linked} linked to a client row, ${data.appointments.length - linked} prospects)`,
);
console.log(`clients referenced by id: ${clientsById.size}`);
